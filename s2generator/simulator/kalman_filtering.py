    from s2generator.utils.visualization import plot_simulator_statistics

    # Generate a sine signal as the reference input.
    seq_length = 1000
    t = np.arange(seq_length)
    sine_signal = np.sin(2 * np.pi * t / 50) + 0.05 * np.random.randn(seq_length)

    simulator = KalmanFilterSimulator(state_order=8, revin=True, random_state=42)
    simulator.fit(sine_signal)

    generated = simulator.transform(num_samples=1, seq_len=seq_length, random_state=7)[
        0
    ]

    print("KalmanFilterSimulator fit summary")
    print(f"  state_order : {simulator.state_order}")
    print(f"  sigma_sq    : {simulator.sigma_sq:.6f}")
    print(f"  coeffs      : {np.array2string(simulator.coeffs, precision=4)}")

    fig = plot_simulator_statistics(
        original_series=sine_signal,
        generated_series=generated,
        residuals=simulator.residuals,
        nlags=50,
        nperseg=128,
    )
